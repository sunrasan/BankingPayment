-- Oracle package and procedures for the banking payment demo.
-- Run after oracle_ddl.sql, connected as the same schema user.

CREATE OR REPLACE PACKAGE BANKING_API_PKG AS
    PROCEDURE TRANSFER_FUNDS (
        P_FROM_ACCOUNT_ID IN  NUMBER,
        P_TO_ACCOUNT_ID   IN  NUMBER,
        P_AMOUNT          IN  NUMBER,
        P_REFERENCE_TEXT  IN  VARCHAR2,
        P_PAYMENT_ID      OUT NUMBER
    );

    PROCEDURE GET_ACCOUNT_SUMMARY (
        P_ACCOUNT_ID        IN  NUMBER,
        P_ACCOUNT_NUMBER    OUT VARCHAR2,
        P_CUSTOMER_NAME     OUT VARCHAR2,
        P_CURRENCY_CODE     OUT VARCHAR2,
        P_AVAILABLE_BALANCE OUT NUMBER,
        P_ACCOUNT_STATUS    OUT VARCHAR2
    );

    PROCEDURE COUNT_PAYMENTS (
        P_TOTAL OUT NUMBER
    );
END BANKING_API_PKG;
/

CREATE OR REPLACE PACKAGE BODY BANKING_API_PKG AS
    PROCEDURE TRANSFER_FUNDS (
        P_FROM_ACCOUNT_ID IN  NUMBER,
        P_TO_ACCOUNT_ID   IN  NUMBER,
        P_AMOUNT          IN  NUMBER,
        P_REFERENCE_TEXT  IN  VARCHAR2,
        P_PAYMENT_ID      OUT NUMBER
    ) AS
        V_FROM_BALANCE BANK_ACCOUNT.AVAILABLE_BALANCE%TYPE;
        V_FROM_STATUS  BANK_ACCOUNT.ACCOUNT_STATUS%TYPE;
        V_FROM_CCY     BANK_ACCOUNT.CURRENCY_CODE%TYPE;
        V_TO_BALANCE   BANK_ACCOUNT.AVAILABLE_BALANCE%TYPE;
        V_TO_STATUS    BANK_ACCOUNT.ACCOUNT_STATUS%TYPE;
        V_TO_CCY       BANK_ACCOUNT.CURRENCY_CODE%TYPE;
    BEGIN
        IF P_AMOUNT IS NULL OR P_AMOUNT <= 0 THEN
            RAISE_APPLICATION_ERROR(-20010, 'Transfer amount must be greater than zero');
        END IF;
        IF P_FROM_ACCOUNT_ID = P_TO_ACCOUNT_ID THEN
            RAISE_APPLICATION_ERROR(-20011, 'Source and destination accounts must differ');
        END IF;
        IF P_REFERENCE_TEXT IS NULL OR LENGTH(TRIM(P_REFERENCE_TEXT)) = 0 THEN
            RAISE_APPLICATION_ERROR(-20012, 'Payment reference is required');
        END IF;

        -- Lock accounts in ascending ID order to reduce deadlock risk.
        IF P_FROM_ACCOUNT_ID < P_TO_ACCOUNT_ID THEN
            SELECT AVAILABLE_BALANCE, ACCOUNT_STATUS, CURRENCY_CODE
              INTO V_FROM_BALANCE, V_FROM_STATUS, V_FROM_CCY
              FROM BANK_ACCOUNT WHERE ACCOUNT_ID = P_FROM_ACCOUNT_ID FOR UPDATE;
            SELECT AVAILABLE_BALANCE, ACCOUNT_STATUS, CURRENCY_CODE
              INTO V_TO_BALANCE, V_TO_STATUS, V_TO_CCY
              FROM BANK_ACCOUNT WHERE ACCOUNT_ID = P_TO_ACCOUNT_ID FOR UPDATE;
        ELSE
            SELECT AVAILABLE_BALANCE, ACCOUNT_STATUS, CURRENCY_CODE
              INTO V_TO_BALANCE, V_TO_STATUS, V_TO_CCY
              FROM BANK_ACCOUNT WHERE ACCOUNT_ID = P_TO_ACCOUNT_ID FOR UPDATE;
            SELECT AVAILABLE_BALANCE, ACCOUNT_STATUS, CURRENCY_CODE
              INTO V_FROM_BALANCE, V_FROM_STATUS, V_FROM_CCY
              FROM BANK_ACCOUNT WHERE ACCOUNT_ID = P_FROM_ACCOUNT_ID FOR UPDATE;
        END IF;

        IF V_FROM_STATUS <> 'ACTIVE' OR V_TO_STATUS <> 'ACTIVE' THEN
            RAISE_APPLICATION_ERROR(-20013, 'Both accounts must be active');
        END IF;
        IF V_FROM_CCY <> V_TO_CCY THEN
            RAISE_APPLICATION_ERROR(-20014, 'Source and destination currencies must match');
        END IF;
        IF V_FROM_BALANCE < P_AMOUNT THEN
            RAISE_APPLICATION_ERROR(-20015, 'Insufficient funds');
        END IF;

        UPDATE BANK_ACCOUNT
           SET AVAILABLE_BALANCE = AVAILABLE_BALANCE - P_AMOUNT
         WHERE ACCOUNT_ID = P_FROM_ACCOUNT_ID;
        UPDATE BANK_ACCOUNT
           SET AVAILABLE_BALANCE = AVAILABLE_BALANCE + P_AMOUNT
         WHERE ACCOUNT_ID = P_TO_ACCOUNT_ID;

        SELECT PAYMENT_TXN_SEQ.NEXTVAL INTO P_PAYMENT_ID FROM DUAL;
        INSERT INTO PAYMENT_TXN (
            PAYMENT_ID, FROM_ACCOUNT_ID, TO_ACCOUNT_ID, AMOUNT,
            CURRENCY_CODE, PAYMENT_STATUS, REFERENCE_TEXT, CREATED_AT
        ) VALUES (
            P_PAYMENT_ID, P_FROM_ACCOUNT_ID, P_TO_ACCOUNT_ID, P_AMOUNT,
            V_FROM_CCY, 'SUCCESS', SUBSTR(TRIM(P_REFERENCE_TEXT), 1, 80), SYSTIMESTAMP
        );

        -- Intentionally no COMMIT: transaction boundary is controlled by caller/session.
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20016, 'Source or destination account was not found');
    END TRANSFER_FUNDS;

    PROCEDURE GET_ACCOUNT_SUMMARY (
        P_ACCOUNT_ID        IN  NUMBER,
        P_ACCOUNT_NUMBER    OUT VARCHAR2,
        P_CUSTOMER_NAME     OUT VARCHAR2,
        P_CURRENCY_CODE     OUT VARCHAR2,
        P_AVAILABLE_BALANCE OUT NUMBER,
        P_ACCOUNT_STATUS    OUT VARCHAR2
    ) AS
    BEGIN
        SELECT ACCOUNT_NUMBER, CUSTOMER_NAME, CURRENCY_CODE,
               AVAILABLE_BALANCE, ACCOUNT_STATUS
          INTO P_ACCOUNT_NUMBER, P_CUSTOMER_NAME, P_CURRENCY_CODE,
               P_AVAILABLE_BALANCE, P_ACCOUNT_STATUS
          FROM V_ACCOUNT_SUMMARY
         WHERE ACCOUNT_ID = P_ACCOUNT_ID;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20017, 'Account not found');
    END GET_ACCOUNT_SUMMARY;

    PROCEDURE COUNT_PAYMENTS (
        P_TOTAL OUT NUMBER
    ) AS
    BEGIN
        SELECT COUNT(*) INTO P_TOTAL FROM PAYMENT_TXN;
    END COUNT_PAYMENTS;
END BANKING_API_PKG;
/
