-- Full setup script for a clean schema. Run with SQL*Plus or SQL Developer Run Script (F5).

-- Banking payment demo: exactly three application tables, two views and sequences.
-- Run as the target application schema user.
-- If re-running, drop the existing objects first or use a clean schema.

CREATE SEQUENCE CUSTOMER_SEQ START WITH 1001 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE BANK_ACCOUNT_SEQ START WITH 5001 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE PAYMENT_TXN_SEQ START WITH 9001 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE CUSTOMER (
    CUSTOMER_ID     NUMBER(19) NOT NULL,
    CUSTOMER_NAME   VARCHAR2(120 CHAR) NOT NULL,
    EMAIL           VARCHAR2(150 CHAR) NOT NULL,
    CUSTOMER_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT UK_CUSTOMER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_CUSTOMER_STATUS CHECK (CUSTOMER_STATUS IN ('ACTIVE','INACTIVE','BLOCKED'))
);

CREATE TABLE BANK_ACCOUNT (
    ACCOUNT_ID         NUMBER(19) NOT NULL,
    CUSTOMER_ID        NUMBER(19) NOT NULL,
    ACCOUNT_NUMBER     VARCHAR2(24 CHAR) NOT NULL,
    ACCOUNT_TYPE       VARCHAR2(20 CHAR) NOT NULL,
    CURRENCY_CODE      CHAR(3 CHAR) DEFAULT 'INR' NOT NULL,
    AVAILABLE_BALANCE  NUMBER(15,2) DEFAULT 0 NOT NULL,
    ACCOUNT_STATUS     VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_BANK_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT UK_BANK_ACCOUNT_NUMBER UNIQUE (ACCOUNT_NUMBER),
    CONSTRAINT FK_ACCOUNT_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    CONSTRAINT CK_ACCOUNT_TYPE CHECK (ACCOUNT_TYPE IN ('SAVINGS','CURRENT')),
    CONSTRAINT CK_ACCOUNT_BALANCE CHECK (AVAILABLE_BALANCE >= 0),
    CONSTRAINT CK_ACCOUNT_STATUS CHECK (ACCOUNT_STATUS IN ('ACTIVE','FROZEN','CLOSED'))
);

CREATE TABLE PAYMENT_TXN (
    PAYMENT_ID       NUMBER(19) NOT NULL,
    FROM_ACCOUNT_ID  NUMBER(19) NOT NULL,
    TO_ACCOUNT_ID    NUMBER(19) NOT NULL,
    AMOUNT           NUMBER(15,2) NOT NULL,
    CURRENCY_CODE    CHAR(3 CHAR) DEFAULT 'INR' NOT NULL,
    PAYMENT_STATUS   VARCHAR2(20 CHAR) NOT NULL,
    REFERENCE_TEXT   VARCHAR2(80 CHAR) NOT NULL,
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PAYMENT_TXN PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT FK_PAYMENT_FROM_ACCOUNT FOREIGN KEY (FROM_ACCOUNT_ID) REFERENCES BANK_ACCOUNT(ACCOUNT_ID),
    CONSTRAINT FK_PAYMENT_TO_ACCOUNT FOREIGN KEY (TO_ACCOUNT_ID) REFERENCES BANK_ACCOUNT(ACCOUNT_ID),
    CONSTRAINT CK_PAYMENT_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_PAYMENT_DIFFERENT_ACCOUNTS CHECK (FROM_ACCOUNT_ID <> TO_ACCOUNT_ID),
    CONSTRAINT CK_PAYMENT_STATUS CHECK (PAYMENT_STATUS IN ('SUCCESS','FAILED','PENDING'))
);

CREATE INDEX IX_ACCOUNT_CUSTOMER ON BANK_ACCOUNT(CUSTOMER_ID);
CREATE INDEX IX_PAYMENT_FROM_DATE ON PAYMENT_TXN(FROM_ACCOUNT_ID, CREATED_AT);
CREATE INDEX IX_PAYMENT_TO_DATE ON PAYMENT_TXN(TO_ACCOUNT_ID, CREATED_AT);

-- View 1: account with customer and current balance.
CREATE OR REPLACE VIEW V_ACCOUNT_SUMMARY AS
SELECT a.ACCOUNT_ID, a.ACCOUNT_NUMBER, a.ACCOUNT_TYPE, a.CURRENCY_CODE,
       a.AVAILABLE_BALANCE, a.ACCOUNT_STATUS,
       c.CUSTOMER_ID, c.CUSTOMER_NAME, c.EMAIL
  FROM BANK_ACCOUNT a
  JOIN CUSTOMER c ON c.CUSTOMER_ID = a.CUSTOMER_ID;

-- View 2: payment history enriched with source/destination account numbers.
CREATE OR REPLACE VIEW V_PAYMENT_DETAILS AS
SELECT p.PAYMENT_ID, p.FROM_ACCOUNT_ID, fa.ACCOUNT_NUMBER AS FROM_ACCOUNT_NUMBER,
       p.TO_ACCOUNT_ID, ta.ACCOUNT_NUMBER AS TO_ACCOUNT_NUMBER,
       p.AMOUNT, p.CURRENCY_CODE, p.PAYMENT_STATUS, p.REFERENCE_TEXT, p.CREATED_AT
  FROM PAYMENT_TXN p
  JOIN BANK_ACCOUNT fa ON fa.ACCOUNT_ID = p.FROM_ACCOUNT_ID
  JOIN BANK_ACCOUNT ta ON ta.ACCOUNT_ID = p.TO_ACCOUNT_ID;

